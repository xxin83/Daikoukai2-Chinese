; ========================================================
; 【Hook 1】拦截“超限安全保护气囊”
; 作用：防止游戏将扩容汉字强行替换为全角空格 ($8140)
; ========================================================
org $C21384
    JML Safe_Airbag          ; 跳转到免死检查区

; ========================================================
; 【Hook 2】拦截“原程序显存地址计算逻辑”
; 作用：接管寻址，将我们的扩容字引向新字库地址
; ========================================================
org $C21396
    JML My_Smart_Text_Logic  ; 跳转到扩容分流器

; ========================================================
; 【核心逻辑区】统一下放到 ROM 末尾的空白区 
; (放置在 FF0000，绝对不会与 EFFF00 的字库抢位置)
; ========================================================
org $FF0000

; --------------------------------------------------------
; 逻辑一：扩容分流器与显存地址计算 (24位跨Bank精准寻址版)
; --------------------------------------------------------
My_Smart_Text_Logic:
    LDA $AD,S        ; 读取刚刚拼装好的字符内码
    
    ; --- 1. 检查是否在我们的新字库范围内 ($87A0 - $99FF) ---
    CMP #$87A0
    BCC Old_Logic    ; 如果小于 $87A0，交给旧逻辑处理
    CMP #$9A00
    BCS Old_Logic    ; 如果大于等于 $9A00，交给旧逻辑处理

    ; --- 2. 剔除原版特权控制码 ($9140 - $9145) ---
    CMP #$9140
    BCC Check_00
    CMP #$9146
    BCC Old_Logic

Check_00:
    ; --- 3. 忽略低位为 00 的垃圾/控制码 ---
    LDA $AD,S
    AND #$00FF
    CMP #$0000
    BEQ Old_Logic

New_Logic:
    ; ========================================================
    ; 新字库：24位精准寻址算法 
    ; 目标起始物理地址：0x2FFF00 -> 对应 SNES 地址：$EFFF00
    ; 公式：Address = $EFFF00 + (Char - $87A0) * 32
    ; ========================================================
    LDA $AD,S
    SEC
    SBC #$87A0       ; 减去基准字码 $87A0
    STA $0C          ; 保存 16 位 Index 到 $0C
    
    ; [步骤 A] 提前提取跨 Bank 溢出量 (即 Index * 32 产生的高位)
    XBA              ; 高低字节互换 (相当于 >> 8)
    AND #$00FF       ; 清除垃圾数据
    LSR A            ; >> 9
    LSR A            ; >> 10
    LSR A            ; >> 11 (完美提取出 Bank 增量)
    STA $0E          ; 暂存在 $0E 中
    
    ; [步骤 B] 计算段内偏移，并加上基址 $FF00
    LDA $0C
    ASL A
    ASL A
    ASL A
    ASL A
    ASL A            ; A = Index * 32
    
    CLC
    ADC #$FF00       ; 加上字库起始偏移地址 $FF00
    STA $0C          ; 存入最终的 16 位偏移地址 (若溢出，会自动产生 Carry 进位标志)
    
    ; [步骤 C] 计算最终 Bank (基准 Bank + 溢出量 + 进位)
    LDA $0E          ; 拿出刚才算好的溢出量
    ADC #$00EF       ; 加上基准 Bank $EF。此时会自动加上步骤 B 产生的 Carry 进位！
    STA $0E          ; 存入 $0E 作为最终 Bank。同时向 $0F 写入 00，保证原版 DMA 不乱！
    
    JML $C213B5      ; 24位物理地址完美拼装完毕，安全跳回原程序去加载显存

; --------------------------------------------------------
; 原版旧字库安全兼容算法 (原封不动还原原版逻辑)
; --------------------------------------------------------
Old_Logic:
    LDA $AD,S
    SEC
    SBC #$8140
    ASL A
    ASL A
    ASL A
    ASL A
    ASL A
    CLC
    ADC #$3000
    STA $0C          ; 存入原版段内偏移
    
    LDA #$00DF       ; 旧字库默认 Bank 为 $DF
    STA $0E          ; $DF 存入 $0E, $00 存入 $0F
    
    JML $C213B5      ; 安全跳回原程序

; --------------------------------------------------------
; 逻辑二：VIP 豁免逻辑 (安全气囊防覆盖)
; --------------------------------------------------------
Safe_Airbag:
    LDA $A7,S        ; 拿出堆栈里因超限即将被原版处刑的字码
    
    ; 检查是不是我们的扩容字？
    CMP #$87A0
    BCC .kill_it     ; 如果不在扩容范围，老老实实按原版去死
    CMP #$9A00
    BCS .kill_it     ; 同上
    
    ; 纯正的扩容字，发放免死金牌，直接放行！绝对不覆盖为 $8140！
    JML $C21389      

.kill_it:
    LDA #$8140       ; 原版处刑代码：强行换成全角空格 ($8140)
    STA $A7,S
    JML $C21389      ; 处刑完毕，返回原程序继续执行